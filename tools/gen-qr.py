#!/usr/bin/env python3
"""Write src/qr.rs: the QR code (error correction M) for the repository URL as rows of bits, for the Try-it screen.
uv run --with segno tools/gen-qr.py <url>"""
import sys, segno
q = segno.make(sys.argv[1], error="m", micro=False)
m = [[1 if c else 0 for c in row] for row in q.matrix]
n = len(m)
rows = ",\n    ".join("0x%016x%016x" % (int("".join(map(str, r)).ljust(128, "0")[:64], 2), int("".join(map(str, r)).ljust(128, "0")[64:], 2)) for r in m)
open("src/qr.rs", "w").write(f"""//! Generated by tools/gen-qr.py: the QR code for {sys.argv[1]} (version {q.version}, {n}x{n} modules).
//! Row r, module c (c < N) = bit 127 - c of ROWS[r].
pub const URL: &str = "{sys.argv[1]}";
pub const N: usize = {n};
pub const ROWS: [u128; {n}] = [
    {rows},
];
""")
print(n, q.version)
