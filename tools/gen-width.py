#!/usr/bin/env python3
"""Generate the character-width tables in src/term.rs from the `wcwidth` package (the same tables pyte uses, so
tools/term-vs-pyte.py compares like with like). Prints Rust; paste between the GENERATED markers in src/term.rs.
Usage: <venv with wcwidth>/bin/python tools/gen-width.py"""
import importlib.metadata
from wcwidth import wcwidth


def ranges(want):
    out, start = [], None
    for cp in range(0xA0, 0x110000):
        hit = not (0xD800 <= cp <= 0xDFFF) and wcwidth(chr(cp)) == want
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, rs):
    body = "".join(("\n    " if i % 6 == 0 else " ") + f"(0x{a:X}, 0x{b:X})," for i, (a, b) in enumerate(rs))
    return f"const {name}: [(u32, u32); {len(rs)}] = [{body}\n];"


print(f"// GENERATED by tools/gen-width.py from wcwidth {importlib.metadata.version('wcwidth')} (0xA0 and up): do not edit by hand")
print(table("ZERO_WIDTH", ranges(0)))
print(table("WIDE", ranges(2)))
print("// END GENERATED")
